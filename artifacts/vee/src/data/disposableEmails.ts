export function isDisposableEmail(email: string): boolean {
  const atIndex = email.lastIndexOf('@');
  if (atIndex === -1) return false;
  const domain = email.slice(atIndex + 1).toLowerCase().trim();
  return DOMAINS[domain] === true;
}

/**
 * Validate email for registration: format + not disposable.
 * Returns an error message key, or null if valid.
 */
export function validateRegistrationEmail(email: string): string | null {
  const trimmed = email.trim();
  if (!trimmed) return 'auth.signup.errorNoEmail';
  if (!/\S+@\S+\.\S+/.test(trimmed)) return 'auth.signup.errorInvalidEmail';
  if (isDisposableEmail(trimmed)) return 'auth.signup.errorDisposableEmail';
  return null;
}
